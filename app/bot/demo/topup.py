"""«Чем добрать» — превращает остаток белка в конкретное действие.

БЫЛО (наивно): «добери 60 г белка ≈ 330 г творога» — считалось ТОЛЬКО по белку. Совет мог
предложить еду, которая пробивает дневные калории или жир, и человек честно выполнял вредный
совет. Для продукта, который продаёт точность, это хуже, чем молчать.

СТАЛО: кандидат обязан закрыть белок И влезть в остаток по ккал И по жиру И в реалистичную
порцию. Три исхода, и все три честные:
  * влезает        → «добери 60 г белка — 190 г куриной грудки (+315 ккал)»;
  * не влезает по ккал/жиру → «калории уже выбраны, добирать через силу не надо»;
  * разрыв огромен → ЧАСТИЧНЫЙ добор («за раз столько не съесть — вот сколько успеешь»).
Раньше последние два схлопывались в одно сообщение, и при разрыве в 155 г бот врал «калории
выбраны», хотя их оставалось 1700.

ПОРЯДОК ПРЕДПОЧТЕНИЯ — ЦЕЛЬНАЯ ЕДА, ПОРОШОК ПОСЛЕДНИМ. Берём первого подходящего по списку, а не
«самого эффективного по калориям»: иначе всегда побеждал бы изолят (он всегда калорийно выгоднее
курицы), и бот превратился бы в продавца добавок. Изолят всплывает сам, когда жир и калории
кончились, — там он действительно единственный честный ответ.

ПОЧЕМУ ДОБИРАЕМ ТОЛЬКО БЕЛОК. Недобор белка при дефиците калорий — единственный недобор, который
реально бьёт по составу тела: организм добирает аминокислоты из мышц. Недобор жиров и углеводов
за один день не стоит ничего и закроется сам. Поэтому жир и углеводы не «добираем» никогда.
"""
from __future__ import annotations

from dataclasses import dataclass

from app.domain.goals import Goal
from app.domain.value_objects import Macros

MIN_GAP_G = 15.0  # меньше — не дёргаем: 10 г белка это шум на фоне суточной цели
MIN_WORTH_G = 20.0  # частичный добор меньше этого — не совет, а издевательство
FULL_TOL_G = 5.0  # добор считается полным, если недокрыл ≤ 5 г белка (это шум)

# Жир — ПОЛ И МЯГКИЙ ПОТОЛОК, а не жёсткая стена. Пускаем добор на 15% выше цели по жиру.
# Иначе выходил абсурд: бот блокировал закрытие белка из-за пары лишних граммов жира — то есть
# жертвовал мышцами ради макроса, дневной перебор которого не стоит ничего. Иерархия жёсткая:
# белок — обязательство, жир — ограничение, углеводы — сдача.
FAT_CEILING = 1.15


@dataclass(frozen=True, slots=True)
class Food:
    """Плотность на 100 г + СВОЙ потолок разовой порции.

    Потолок обязан быть свой у каждого: общий «400 г» бессмыслен для порошка — бот на голубом
    глазу советовал 172 г изолята (шесть мерных ложек) как «полное закрытие разрыва».

    ponytail: короткий курируемый список — источники белка не меняются десятилетиями, а подсказка
    нужна мгновенно и бесплатно (LLM тут стоил бы денег и секунд). Апгрейд, если понадобится
    учитывать «что есть дома» — спросить LLM.
    """

    name: str
    kcal: float
    protein: float
    fat: float
    max_g: float  # сколько этого человек реально съест/выпьет за один присест


# ПОРЯДОК = ПРЕДПОЧТЕНИЕ. Цельная еда первой, изолят последним (см. шапку модуля).
FOODS = (
    Food("куриной грудки", 165, 31.0, 3.6, max_g=400),
    Food("тунца в собственном соку", 108, 24.0, 1.0, max_g=300),  # ~2 банки
    Food("творога 2%", 103, 18.0, 2.0, max_g=400),
    Food("греческого йогурта 2%", 73, 10.0, 2.0, max_g=500),
    Food("яичных белков", 52, 11.0, 0.2, max_g=300),
    Food("протеинового изолята", 375, 90.0, 1.5, max_g=60),  # 2 мерные ложки, не шесть
)


@dataclass(frozen=True, slots=True)
class Topup:
    gap_g: float  # сколько белка не хватает до цели
    food: Food | None  # чем добрать; None — не влезает ничего
    grams: float
    kcal: float  # сколько ккал добавит порция
    protein_add: float  # сколько белка реально закроет (< gap_g при частичном доборе)
    kcal_left: float  # остаток калорий ПОСЛЕ добора
    partial: bool  # True — разрыв за раз не закрыть, это «сколько успеешь»
    reason: str = ""  # почему нечем добрать: "kcal" | "fat". Врать про причину нельзя


def _fit_grams(food: Food, gap: float, kcal_left: float, fat_left: float) -> float:
    """Сколько граммов реально влезает: по разрыву белка, по ккал, по жиру, по разовой порции.

    Округление ВНИЗ до десятков — принципиально. Округление вверх пробивало лимит: при остатке
    жира 1.0 г бот советовал 70 г изолята (= 1.05 г жира) и сам же нарушал ограничение.
    """
    limits = [food.max_g, gap / (food.protein / 100)]
    if food.kcal:
        limits.append(kcal_left / (food.kcal / 100))
    if food.fat:
        limits.append(fat_left / (food.fat / 100))
    return max(0.0, min(limits) // 10 * 10)


def suggest(consumed: Macros, goal: Goal) -> Topup | None:
    """Подобрать добор белка, не пробивая остаток по ккал и жиру. None — добор не нужен."""
    gap = goal.protein_g - consumed.protein
    if gap < MIN_GAP_G:
        return None  # белок в порядке — молчим

    kcal_left = max(0.0, goal.daily_kcal - consumed.kcal)
    fat_left = max(0.0, goal.fat_g * FAT_CEILING - consumed.fat)

    # Все величины считаем от УЖЕ округлённых граммов — иначе обещаем одно, а порция даёт другое.
    best: tuple[Food, float, float] | None = None  # (еда, граммы, закрытый белок)
    for food in FOODS:
        grams = _fit_grams(food, gap, kcal_left, fat_left)
        protein = grams * food.protein / 100
        if protein >= gap - FULL_TOL_G:  # закрывает разрыв → берём ПЕРВОГО подходящего по списку
            best = (food, grams, protein)
            break
        if best is None or protein > best[2]:  # иначе копим лучшего частичного
            best = (food, grams, protein)

    assert best is not None  # FOODS непуст → цикл всегда что-то положил
    food, grams, protein = best
    if protein < MIN_WORTH_G:
        # Места нет. НАЗВАТЬ ИСТИННУЮ ПРИЧИНУ: раньше бот при исчерпанном жире всё равно писал
        # «калории уже выбраны», хотя их оставалась тысяча. Врать про причину — то же враньё.
        reason = "kcal" if kcal_left < 150 else "fat"
        return Topup(gap, None, 0, 0, 0, round(kcal_left), partial=False, reason=reason)

    kcal = grams * food.kcal / 100
    return Topup(
        gap_g=gap,
        food=food,
        grams=grams,
        kcal=round(kcal),
        protein_add=round(protein),
        kcal_left=round(kcal_left - kcal),
        partial=protein < gap - FULL_TOL_G,
    )


def line(consumed: Macros, goal: Goal) -> str:
    """Готовая строка для любого дизайна. Пустая — если добирать нечего."""
    t = suggest(consumed, goal)
    if t is None:
        return ""
    if t.food is None:
        # Честно: белка мало, но добрать нечем. Врать «съешь ещё» нельзя, стыдить — тем более.
        # И причину называть настоящую: калории и жир — разные стены.
        if t.reason == "fat":
            return (
                f"<p>🥩 Белка не хватает <b>{round(t.gap_g)} г</b>, но жир уже перебран — "
                "любой добор уведёт его ещё выше. Оставь как есть, добери завтра с утра.</p>"
            )
        return (
            f"<p>🥩 Белка не хватает <b>{round(t.gap_g)} г</b>, но калории на сегодня уже "
            "выбраны. Добирать через силу не надо — важнее среднее за неделю.</p>"
        )
    if t.partial:
        return (
            f"<p>💡 Белка не хватает <b>{round(t.gap_g)} г</b> — за раз столько не съесть. "
            f"Сколько влезет: {t.grams:.0f} г {t.food.name} = +{t.protein_add:.0f} г "
            f"(+{t.kcal:.0f} ккал). Остальное подтяни завтра.</p>"
        )
    return (
        f"<p>💡 Добери <b>{round(t.gap_g)} г белка</b> — это {t.grams:.0f} г {t.food.name} "
        f"(+{t.kcal:.0f} ккал, ещё {t.kcal_left:.0f} останется).</p>"
    )


def demo() -> None:
    """Runnable-чек. Каждая ветка ловит реальный баг, который тут уже был."""
    goal = Goal(daily_kcal=2200, protein_g=165, fat_g=61, carb_g=248)

    # 1. Белок в норме → молчим.
    assert suggest(Macros(1500, 160, 40, 150), goal) is None

    # 2. Места вдоволь → цельная еда, а НЕ порошок (иначе бот — продавец добавок).
    t = suggest(Macros(1000, 60, 20, 100), goal)
    assert t is not None and t.food is not None
    assert t.food.name == "куриной грудки", f"при свободном дне должна быть еда, а не {t.food.name}"
    assert t.kcal <= 2200 - 1000, "совет не смеет пробивать остаток калорий"

    # 3. Жир на цели, калорий полно → добор ОБЯЗАН состояться: жир это мягкий потолок, а белок —
    #    обязательство. Блокировать мышцы ради пары граммов жира — абсурд (был такой баг).
    at_fat_goal = Macros(1200, 100, goal.fat_g, 150)
    t = suggest(at_fat_goal, goal)
    assert t is not None and t.food is not None, "белок нельзя приносить в жертву жиру"
    fat_after = at_fat_goal.fat + t.grams * t.food.fat / 100
    assert fat_after <= goal.fat_g * FAT_CEILING + 0.01, "добор ушёл выше мягкого потолка жира"

    # 4. Калории выбраны → добирать нечем, и причина ИМЕННО калории.
    over = Macros(2200, 80, 40, 250)
    t = suggest(over, goal)
    assert t is not None and t.food is None and t.reason == "kcal"
    assert "калории" in line(over, goal)

    # 4b. Жир перебран, калорий полно → причина ЖИР, а не калории. Врать про причину нельзя.
    fat_blown = Macros(900, 80, goal.fat_g * 1.4, 100)
    t = suggest(fat_blown, goal)
    assert t is not None and t.food is None and t.reason == "fat", "назвал не ту стену"
    assert "жир" in line(fat_blown, goal) and "калории" not in line(fat_blown, goal)

    # 5. Разрыв огромен → ЧАСТИЧНЫЙ добор, а не ложное «калории выбраны» (был баг: врал).
    huge = Macros(500, 10, 10, 50)
    t = suggest(huge, goal)
    assert t is not None and t.food is not None and t.partial
    assert t.grams <= t.food.max_g, "порция не смеет превышать разовый потолок продукта"
    assert t.protein_add < t.gap_g, "частичный добор обязан признаваться частичным"
    assert "калории" not in line(huge, goal), "калорий полно — врать про них нельзя"

    print("topup: ok")


if __name__ == "__main__":
    demo()
