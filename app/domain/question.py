"""Похоже ли сообщение на вопрос (FR-45, D-MA-27).

Решает только форму фразы, а не смысл: проверка идёт ПОСЛЕ разбора и лишь для того, что
разбор счёл `unknown`. Еду отсюда не отличить и не нужно — до проверки она не доходит.

ponytail: «?» в конце или слово-вопрос первым. Мажет на «расскажи про мою неделю» (вопрос без
вопроса) — такой текст остаётся «не понял», как раньше; путь апгрейда — поле в схеме разбора.
"""
from __future__ import annotations

import re

# Первым словом — почти всегда вопрос. «как» и «что» в начале фразы о еде не встречаются: еда
# начинается с продукта или числа, а разбор её до сюда и не пустит.
_ASKING = frozenset({
    "почему", "зачем", "отчего", "как", "какой", "какая", "какое", "какие", "каких", "каким",
    "какую", "что", "чем", "чего", "сколько", "где", "когда", "куда", "откуда", "можно", "стоит",
    "нормально", "правда", "ли", "разве", "неужели",
})
_WORD = re.compile(r"[а-яёa-z]+")


# FR-45 (б): сильный зачин — фраза почти наверняка вопрос, даже если в ней еда («можно ли есть
# банан на ночь?»). Разбор такую фразу честно пишет приёмом — фантомный банан. Проверка ДО
# разбора; промпт разбора не трогаем (основной путь, правка — платный eval).
_STRONG = re.compile(
    r"^(?:(?:а|и|ну)\s+)?(?:стоит\s+ли|можно\s+ли|можно\s+мне|нужно\s+ли"
    r"|сколько\s+(?:калорий|ккал|белка|жиров|жира|углеводов)|чем\s+(?:заменить|добрать)"
    r"|почему|как\s+(?:лучше|быстрее|мне)|что\s+(?:лучше|съесть|поесть)|полезн\w*|вредн\w*)\b"
)


# Количество — признак записи: «гречка 150 г?», «а полпорции?». Цифра с единицей или без.
_AMOUNT = re.compile(
    r"\d+(?:[.,]\d+)?\s*(?:гр|г|кг|мл|л|шт|порц)?|\bпол\s*-?\s*порци|\bполовин", re.IGNORECASE
)
# Зачины, где количество — часть вопроса: «сколько белка в 150 г гречки?».
_AMOUNT_OK = re.compile(r"^(?:(?:а|и|ну)\s+)?(?:сколько|чем|почему)\b")


def has_amount(text: str) -> bool:
    return _AMOUNT.search(text) is not None


def strong_question(text: str) -> bool:
    """Кончается на «?» И начинается с сильного зачина — к ассистенту без разбора.
    Оба условия сразу: «гречка 150 г?» зачина не имеет и остаётся записью. Количество во фразе
    снимает зачин (идёт разбором), кроме «сколько/чем/почему»."""
    low = text.strip().lower()
    if not low.endswith("?") or _STRONG.match(low) is None:
        return False
    return not has_amount(low) or _AMOUNT_OK.match(low) is not None


def looks_like_question(text: str) -> bool:
    """Кончается на «?» или начинается со слова-вопроса; в тексте есть хотя бы одна буква."""
    low = text.strip().lower()
    words = _WORD.findall(low)
    if not words:
        return False
    return low.endswith("?") or words[0] in _ASKING


def demo() -> None:
    """Runnable-чек: вопросы — да, болтовня и пустое — нет."""
    assert looks_like_question("почему я не худею")
    assert looks_like_question("Что съесть на ужин, чтобы добрать белок")
    assert looks_like_question("а белка мне хватает?")
    assert looks_like_question("  ок?  ")
    assert not looks_like_question("привет")
    assert not looks_like_question("расскажи про мою неделю")  # цена правила — см. докстринг
    assert not looks_like_question("???")
    assert not looks_like_question("")
    assert not looks_like_question("какао-порошок 5 г")  # «какао» ≠ «как»: слово целиком

    assert strong_question("Можно ли есть банан на ночь?")
    assert strong_question("а стоит ли есть гречку вечером?")
    assert strong_question("сколько белка мне нужно?")
    assert strong_question("Полезна ли гречка?")
    assert not strong_question("можно ли есть банан на ночь")  # без «?» — через разбор
    assert not strong_question("гречка 150 г?")  # количество без зачина — запись
    assert not strong_question("можно банан?")  # «можно» без «ли/мне» — слабый зачин
    assert not strong_question("какао 5 г?")
    assert not strong_question("можно ли съесть 200 г творога?")  # количество — разбором
    assert not strong_question("стоит ли есть половину пиццы?")
    assert strong_question("сколько белка в 150 г гречки?")  # тут количество — часть вопроса
    assert has_amount("гречка 150 г?") and has_amount("а полпорции?") and has_amount("1,5 кг")
    assert not has_amount("а гречка?")
    print("вопрос по форме: ок")


if __name__ == "__main__":
    demo()
