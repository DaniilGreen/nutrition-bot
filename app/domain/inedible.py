"""Пояснение к весу, когда несъедобное вычтено (INV-7.1, багрепорт #34).

Человек сказал «куриный окорок 400 грамм с костью», а в ленте увидел «260 г» —
и прочитал это как поломку. Вычет верен: кость не едят, и 400 г мяса завысили бы
приём в полтора раза. Неверно было молчать об этом.

Здесь считается только ТЕКСТ пояснения. Промптом это не чинится: правило про
вычет кости громкое и верное, модель за него держится — проверено тремя заходами
09.09.2026. Значит объясняет приложение.
"""
from __future__ import annotations

import math
import re

from app.domain.naming import _coverage
from app.domain.stated_amount import stated_grams

# Вид несъедобного → слова, которыми его называют. Порядок важен: «креветки с головой в
# панцире» — это голова (доля меньше), а не просто панцирь. «Без панциря», «очищенные» —
# не маркеры: они говорят ровно обратное.
_KINDS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("голова", ("с головой", "с головами")),
    ("панцирь", ("в панцире", "в панцирях", "с панцирем")),
    ("раковина", ("в раковин", "в ракушк", "с ракушк", "в створк")),
    ("скорлупа", ("в скорлупе", "со скорлупой")),
    ("косточка", ("с косточк",)),
    ("кость", ("с костью", "с костями", "на кости")),
    ("кожура", ("в кожуре", "с кожурой", "неочищ", "нечищ")),
)
# Слова, которыми человек сам сообщает, что взвесил вместе с несъедобным.
_MARKERS = tuple(m for _, words in _KINDS for m in words)

# FR-34.2: доля съедобного. На фото её считает приложение, а не модель: карточка обещает
# число ДО записи, и запись обязана его сдержать (D-MA-30). Доли — USDA SR, поле «Refuse».
# ponytail: таблица грубая (±10%) и короткая; вид по умолчанию закрывает остальное. Потолок —
# частые вычеты на редкой еде; путь — доля съедобного у продукта каталога.
_DEFAULT_YIELD = {
    "голова": 0.6, "панцирь": 0.6, "раковина": 0.3, "скорлупа": 0.5,
    "косточка": 0.85, "кость": 0.7, "кожура": 0.75,
}
# (основа продукта, виды или None — любой, доля). Первая подходящая строка побеждает.
_PRODUCT_YIELD: tuple[tuple[str, tuple[str, ...] | None, float], ...] = (
    (r"кревет", ("голова",), 0.5),          # голова — почти половина креветки
    (r"без голов", None, 0.83),             # «креветки без головы в панцире» — только панцирь
    (r"кревет", None, 0.6),                 # в панцире без слова «голова» — середина 0,5…0,85
    (r"\bрак(и|ов|а)?\b", None, 0.2),
    (r"краб", None, 0.35),
    (r"устриц", None, 0.15),
    (r"яйц|яиц|яйк", ("скорлупа",), 0.88),
    (r"фисташ", None, 0.53),
    (r"арахис", None, 0.73),
    (r"грецк|фундук", None, 0.45),
    (r"крыл", ("кость",), 0.55),
    (r"бедр|бедер", ("кость",), 0.75),
    (r"банан", None, 0.64),
    (r"мандарин|апельсин", None, 0.74),
    (r"арбуз|дын", None, 0.5),
    (r"ананас", None, 0.5),
    (r"гранат", None, 0.55),
    (r"авокадо", None, 0.7),
    (r"картоф|картош", ("кожура",), 0.88),
    (r"олив|маслин", ("косточка",), 0.8),
)
# Составное блюдо: маркер относится к начинке, а не ко всей массе («салат с креветками в
# панцире», «пицца с косточками оливок») — вычитать долю из всей тарелки нельзя.
_DISHES = frozenset({
    "салат", "пицца", "суп", "паста", "плов", "рагу", "бургер", "ролл", "роллы", "шаурма",
    "бутерброд", "сэндвич", "омлет", "паэлья", "ризотто", "лапша", "вок", "поке", "боул",
    "запеканка", "пирог", "тако", "буррито", "сет", "ассорти", "солянка", "уха",
})
_ROUGH = ("неочищ", "нечищ")  # «неочищенный рис» — не про несъедобное: только продукты таблицы
# Имя для фразы разбора, когда вес уже съедобный: чем заменить маркер.
_PEELED = {
    "голова": "без головы", "панцирь": "без панциря", "раковина": "без раковин",
    "скорлупа": "без скорлупы", "косточка": "без косточки", "кость": "без кости",
    "кожура": "без кожуры",
}
# Ниже этой доли расхождение — не вычет, а разброс оценки: объяснять нечего.
_MIN_DROP = 0.05


def _low(text: str) -> str:
    return (text or "").lower().replace("ё", "е")


def _kinds(name: str) -> list[str]:
    low = _low(name)
    return [k for k, words in _KINDS if any(w in low for w in words)]


def edible_ratio(name: str) -> float | None:
    """Доля съедобного у позиции фото или None, если в имени нет несъедобного (FR-34.2)."""
    kinds = _kinds(name)
    low = _low(name)
    first = (re.findall(r"[^\W\d_]+", low) or [""])[0]
    if not kinds or first in _DISHES:
        return None
    for pattern, only, ratio in _PRODUCT_YIELD:
        if re.search(pattern, low) and (only is None or any(k in only for k in kinds)):
            return ratio
    rough_only = kinds == ["кожура"] and not any(
        w in low for w in dict(_KINDS)["кожура"] if w not in _ROUGH
    )
    if rough_only:
        return None
    return min(_DEFAULT_YIELD[k] for k in kinds)


def edible_grams(name: str, grams: float) -> float | None:
    """Съедобные граммы позиции фото — ОДНО число на карточку и на запись (FR-34.2).
    Округление — половина вверх, как `Math.round` в шторке аппки."""
    ratio = edible_ratio(name)
    if ratio is None or grams <= 0:
        return None
    return float(math.floor(grams * ratio + 0.5))


_SEAFOOD = ("голова", "панцирь", "раковина")


def peeled_name(name: str) -> str:
    """«Без вычета — уже чищено»: «креветки отварные в панцире» → «креветки отварные очищенные»
    (у морепродуктов), у прочего — «без кости», «без кожуры». Вычитать больше нечего."""
    if any(k in _SEAFOOD for k in _kinds(name)):
        out = name
        for _, words in _KINDS[:3]:
            for w in words:
                out = re.sub(rf"(?i)\s*\b{w}\w*", "", out)
        return re.sub(r"\s+", " ", f"{out.strip()} очищенные").strip()
    return edible_name(name)


def edible_name(name: str) -> str:
    """Имя для фразы разбора, когда вес уже съедобный (FR-34.2): «креветки отварные в панцире»
    → «креветки отварные без панциря». Маркера нет — ни приложение, ни модель не вычтут ещё раз,
    и имя с панцирем не уходит в каталог (INV-3)."""
    out, tail = name, []
    for kind, words in _KINDS:
        for w in words:
            if w in ("неочищ", "нечищ"):  # «неочищенные» → «очищенные»: окончание сохраняем
                out = re.sub(rf"(?i)\bне(?={w[2:]})", "", out)
                continue
            out, n = re.subn(rf"(?i)\s*\b{w}\w*", "", out)
            if n and _PEELED[kind] not in tail:
                tail.append(_PEELED[kind])
    return re.sub(r"\s+", " ", " ".join([out.strip(), *tail])).strip()


def _said_inedible(text: str) -> bool:
    low = _low(text)
    return any(m in low for m in _MARKERS)


def explain(raw_input: str, item_name: str, grams: float) -> str | None:
    """Пояснение к весу или None, если объяснять нечего.

    Срабатывает узко и только там, где человеку есть что сверять: он назвал вес,
    назвал несъедобное, а записалось меньше. Всё остальное — обычная оценка,
    и приписка к ней была бы шумом.
    """
    if not raw_input or grams <= 0:
        return None
    raw_input = _own_part(raw_input, item_name)
    if not raw_input or not _said_inedible(raw_input):
        return None
    said = stated_grams(raw_input)
    if said is None or said <= grams:
        return None
    if (said - grams) / said < _MIN_DROP:
        return None
    part = _what(raw_input)
    return f"съедобное из {said:g} г {part}"


def _own_part(text: str, item_name: str) -> str | None:
    """Кусок ввода, который относится к этой позиции.

    Фраза из нескольких позиций («бёдра с костью 300 г, огурец 50 г») раньше
    проверялась целиком, и «съедобное из 300 г с костью» прилипало к огурцу и
    маслу (фото 17.09.2026). Делим по запятым и берём кусок, больше всего
    похожий на имя позиции; ни один не похож — пояснять не о чем.

    ponytail: делим только по запятой и точке с запятой. «Бедро с костью и
    огурец» одним куском всё ещё спутает позиции; «и» внутри одной позиции
    («с костью и с кожей») встречается чаще, чем как разделитель.
    """
    parts = [p.strip() for p in re.split(r"[,;\n]+", text) if p.strip()]
    if len(parts) <= 1:
        return text
    score, best = max((_coverage(item_name, p), p) for p in parts)
    return best if score > 0 else None


def _what(text: str) -> str:
    """Чем именно был вес — его же словами, чтобы пояснение читалось как ответ."""
    low = _low(text)
    if "панцир" in low or "голов" in low:
        return "с головой" if "голов" in low else "в панцире"
    if "раковин" in low or "ракушк" in low or "створк" in low:
        return "в раковинах"
    if "скорлуп" in low:
        return "в скорлупе"
    if "кожур" in low:
        return "с кожурой"
    if "косточк" in low:
        return "с косточкой"
    if "неочищ" in low or "нечищ" in low:
        return "неочищенного"
    return "с костью"


def demo() -> None:
    """Runnable-чек: срабатывает узко и не шумит на обычных записях."""
    # Тот самый багрепорт #34.
    assert explain("куриный окорок 400 грамм с костью и с кожей",
                   "куриный окорок с кожей", 260) == "съедобное из 400 г с костью"
    # Вес назван, но про несъедобное — ни слова: вычета не было, объяснять нечего.
    assert explain("куриный окорок 400 грамм", "куриный окорок", 400) is None
    # Про кость сказано, но записали столько же — тоже нечего.
    assert explain("рёбра 300 г с костью", "рёбра", 300) is None
    # Записали БОЛЬШЕ названного — это не вычет, молчим.
    assert explain("рёбра 300 г с костью", "рёбра", 350) is None
    # Расхождение в пределах разброса оценки — не приписка, а шум.
    assert explain("рёбра 300 г с костью", "рёбра", 292) is None
    # Веса не назвали — сверять человеку не с чем.
    assert explain("две куриные ножки с костью", "куриная ножка", 120) is None
    # Другие виды несъедобного говорят его же словами.
    assert explain("мандарины 200 г с кожурой", "мандарин", 150) == "съедобное из 200 г с кожурой"
    assert explain("фисташки 100 г в скорлупе", "фисташки", 55) == "съедобное из 100 г в скорлупе"
    assert explain("", "что-то", 100) is None
    # Фраза из нескольких позиций: пояснение — только у своей (фото 17.09.2026).
    plate = ("куриные бёдра запечённые с костью 300 г, картофель запечённый дольками 320 г, "
             "огурец свежий 50 г, масло подсолнечное 5 г")
    assert explain(plate, "куриные бёдра запечённые с кожей", 210) == (
        "съедобное из 300 г с костью"
    )
    assert explain(plate, "огурец свежий", 50) is None
    assert explain(plate, "масло подсолнечное", 5) is None
    assert explain(plate, "нечто совсем другое", 5) is None
    # Креветки 25.10.2026: панцирь — тоже несъедобное, и пояснение обязано быть.
    assert explain("креветки отварные в панцире 341 г", "креветки отварные в панцире",
                   205) == "съедобное из 341 г в панцире"
    assert explain("креветки с головой 500 г", "креветки", 250) == "съедобное из 500 г с головой"
    assert explain("мидии в раковинах 400 г", "мидии", 120) == "съедобное из 400 г в раковинах"

    # FR-34.2: доля съедобного — одна на карточку и запись.
    assert edible_grams("креветки отварные в панцире", 341) == 205
    assert edible_grams("креветки отварные в панцире", 340) == 204
    assert edible_grams("креветки с головой в панцире", 400) == 200
    assert edible_grams("креветки неочищенные", 100) == 60
    assert edible_grams("куриные бёдра запечённые с костью", 300) == 225
    assert edible_grams("куриная голень с костью", 200) == 140
    assert edible_grams("куриные крылья с костью", 200) == 110
    assert edible_grams("яйцо варёное в скорлупе", 60) == 53
    assert edible_grams("мандарин в кожуре", 100) == 74
    assert edible_grams("раки варёные в панцире", 500) == 100
    assert edible_grams("креветки отварные", 341) is None
    assert edible_grams("креветки без панциря", 341) is None
    assert edible_grams("бедро с кожей", 200) is None          # кожа съедобна, не «кожура»
    assert edible_grams("креветки в панцире", 0) is None
    assert edible_ratio("курица") is None and edible_ratio("рёбра на кости") == 0.7
    # «Уже чищено»: имя без маркера — и вычитать больше нечего.
    assert edible_name("креветки отварные в панцире") == "креветки отварные без панциря"
    assert edible_name("креветки с головой в панцире") == "креветки без головы без панциря"
    assert edible_name("креветки неочищенные") == "креветки очищенные"
    assert edible_name("Куриные бёдра с костью запечённые") == "Куриные бёдра запечённые без кости"
    assert edible_name("мидии в ракушках") == "мидии без раковин"
    assert peeled_name("креветки отварные в панцире") == "креветки отварные очищенные"
    assert peeled_name("креветки с головой в панцире") == "креветки очищенные"
    assert peeled_name("бедро на кости") == "бедро без кости"
    for n in ("креветки отварные в панцире", "креветки неочищенные", "оливки с косточкой",
              "фисташки в скорлупе", "бедро на кости", "банан в кожуре", "креветки нечищеные"):
        assert edible_grams(peeled_name(n), 100) is None, n
        assert edible_grams(edible_name(n), 100) is None, n
    # Ревью 26.10: «неочищенный» — только у продуктов таблицы; составное блюдо — без вычета.
    assert edible_ratio("рис неочищенный") is None and edible_ratio("банан неочищенный") == 0.64
    assert edible_ratio("салат с креветками в панцире") is None
    assert edible_ratio("пицца с косточками оливок") is None
    assert edible_grams("креветки без головы в панцире", 100) == 83
    print("пояснение к весу: ок")


if __name__ == "__main__":
    demo()
