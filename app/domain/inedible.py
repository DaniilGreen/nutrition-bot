"""Пояснение к весу, когда несъедобное вычтено (INV-7.1, багрепорт #34).

Человек сказал «куриный окорок 400 грамм с костью», а в ленте увидел «260 г» —
и прочитал это как поломку. Вычет верен: кость не едят, и 400 г мяса завысили бы
приём в полтора раза. Неверно было молчать об этом.

Здесь считается только ТЕКСТ пояснения. Промптом это не чинится: правило про
вычет кости громкое и верное, модель за него держится — проверено тремя заходами
09.09.2026. Значит объясняет приложение.
"""
from __future__ import annotations

from app.domain.stated_amount import stated_grams

# Слова, которыми человек сам сообщает, что взвесил вместе с несъедобным.
_MARKERS = (
    "с костью", "с костями", "на кости", "с кожурой", "в кожуре",
    "в скорлупе", "со скорлупой", "неочищ", "нечищ", "с косточкой", "с косточками",
)
# Ниже этой доли расхождение — не вычет, а разброс оценки: объяснять нечего.
_MIN_DROP = 0.05


def _said_inedible(text: str) -> bool:
    low = text.lower().replace("ё", "е")
    return any(m.replace("ё", "е") in low for m in _MARKERS)


def explain(raw_input: str, item_name: str, grams: float) -> str | None:
    """Пояснение к весу или None, если объяснять нечего.

    Срабатывает узко и только там, где человеку есть что сверять: он назвал вес,
    назвал несъедобное, а записалось меньше. Всё остальное — обычная оценка,
    и приписка к ней была бы шумом.
    """
    if not raw_input or grams <= 0 or not _said_inedible(raw_input):
        return None
    said = stated_grams(raw_input)
    if said is None or said <= grams:
        return None
    if (said - grams) / said < _MIN_DROP:
        return None
    part = _what(raw_input)
    return f"съедобное из {said:g} г {part}"


def _what(text: str) -> str:
    """Чем именно был вес — его же словами, чтобы пояснение читалось как ответ."""
    low = text.lower().replace("ё", "е")
    if "скорлуп" in low:
        return "в скорлупе"
    if "кожур" in low:
        return "с кожурой"
    if "косточк" in low:
        return "с косточкой"
    if "неочищ" in low or "нечищ" in low:
        return "неочищенного"
    return "с костью"


def demo() -> None:
    """Runnable-чек: срабатывает узко и не шумит на обычных записях."""
    # Тот самый багрепорт #34.
    assert explain("куриный окорок 400 грамм с костью и с кожей",
                   "куриный окорок с кожей", 260) == "съедобное из 400 г с костью"
    # Вес назван, но про несъедобное — ни слова: вычета не было, объяснять нечего.
    assert explain("куриный окорок 400 грамм", "куриный окорок", 400) is None
    # Про кость сказано, но записали столько же — тоже нечего.
    assert explain("рёбра 300 г с костью", "рёбра", 300) is None
    # Записали БОЛЬШЕ названного — это не вычет, молчим.
    assert explain("рёбра 300 г с костью", "рёбра", 350) is None
    # Расхождение в пределах разброса оценки — не приписка, а шум.
    assert explain("рёбра 300 г с костью", "рёбра", 292) is None
    # Веса не назвали — сверять человеку не с чем.
    assert explain("две куриные ножки с костью", "куриная ножка", 120) is None
    # Другие виды несъедобного говорят его же словами.
    assert explain("мандарины 200 г с кожурой", "мандарин", 150) == "съедобное из 200 г с кожурой"
    assert explain("фисташки 100 г в скорлупе", "фисташки", 55) == "съедобное из 100 г в скорлупе"
    assert explain("", "что-то", 100) is None
    print("пояснение к весу: ок")


if __name__ == "__main__":
    demo()
