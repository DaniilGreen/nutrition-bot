"""Объём или вес, названный прямо в имени позиции.

Реальный случай: «Пиво Сайгон 0.3 л» записалось как **500 г** и 210 ккал
вместо ~300 г и ~130. Модель поставила объём в имя, а граммовку взяла свою
оценку «кружка пива». Имя и цифра разошлись, и цифра оказалась вдвое больше.

Это защита второго слоя. Первый — правило в промпте; но модель будет ошибаться
снова, а INV-7 ставит явный вес первым шагом цепочки. Если человек (или сама
модель) назвал объём, он и есть явный вес.

Домен: чистый разбор строки.
"""
from __future__ import annotations

import re

# Множители к граммам. Для напитков объём ≈ масса — этого достаточно (INV-7).
_UNITS = {
    "мл": 1.0, "ml": 1.0,
    "л": 1000.0, "l": 1000.0, "литр": 1000.0, "литра": 1000.0, "литров": 1000.0,
    "г": 1.0, "гр": 1.0, "g": 1.0, "грамм": 1.0, "грамма": 1.0, "граммов": 1.0,
    "кг": 1000.0, "kg": 1000.0,
}

# Число, затем единица. Единица обязательна: «творог 5%» и «молоко 3.2%» —
# это жирность, а не порция, и подставлять их в граммы нельзя.
_RE = re.compile(
    r"(?<![\d.,%])(\d{1,4}(?:[.,]\d{1,3})?)\s*"
    r"(мл|ml|литров|литра|литр|л|l|граммов|грамма|грамм|гр|г|g|кг|kg)\b",
    re.IGNORECASE,
)

# Разумные пределы одной позиции: ниже — приправа, выше — опечатка.
MIN_G, MAX_G = 1.0, 5000.0


def stated_grams(name: str) -> float | None:
    """Вес в граммах, названный в строке. None — если не назван или невероятен."""
    for num, unit in _RE.findall(name or ""):
        grams = float(num.replace(",", ".")) * _UNITS[unit.lower()]
        if MIN_G <= grams <= MAX_G:
            return round(grams, 1)
    return None


def demo() -> None:
    """Runnable-чек: реальный случай и ловушки, на которых легко ошибиться."""
    # Тот самый баг.
    assert stated_grams("Пиво Сайгон 0.3 л") == 300
    assert stated_grams("Пиво Сайгон 0,5 л") == 500
    assert stated_grams("кола 500 мл") == 500
    assert stated_grams("рис отварной 220 г") == 220
    assert stated_grams("мясо 1.2 кг") == 1200

    # Жирность и проценты — НЕ порция. Здесь ошибка стоила бы вдвое.
    assert stated_grams("молоко 3.2%") is None
    assert stated_grams("Творог 5%") is None
    assert stated_grams("пиво 4,5% алк") is None

    # Единица обязательна: «03» без единицы разбирать нельзя, это догадка.
    assert stated_grams("Пиво Сайгон 03") is None
    assert stated_grams("яйца 2") is None

    # Невероятное отбрасываем, а не записываем.
    assert stated_grams("сахар 0.2 г") is None      # ниже порога
    assert stated_grams("вода 10 л") is None        # выше порога
    assert stated_grams("") is None

    # Первое вхождение с единицей, а не последнее число в строке.
    assert stated_grams("молоко 3.2% 200 мл") == 200
    print("объём, названный в имени: ок")


if __name__ == "__main__":
    demo()
